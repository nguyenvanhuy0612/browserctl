// @ts-check
// Extracts the parts of the pinned playwright-core that the extension runs, into
// extension/generated/: Playwright's injected script (as a class, instantiated per frame by the
// DOM-lane runtime) and its US keyboard layout. Run after installing or upgrading playwright-core.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const corePackage = require.resolve("playwright-core/package.json");
const version = JSON.parse(fs.readFileSync(corePackage, "utf8")).version;
const bundle = fs.readFileSync(path.join(path.dirname(corePackage), "lib/coreBundle.js"), "utf8");
const outDir = path.join(root, "extension/generated");

/** @param {string} startMarker @param {string} endMarker @param {number} from */
function slice(startMarker, endMarker, from = 0) {
  const start = bundle.indexOf(startMarker, from);
  if (start < 0) throw new Error(`playwright-core ${version}: marker not found: ${startMarker}`);
  const end = bundle.indexOf(endMarker, start + startMarker.length);
  if (end < 0) throw new Error(`playwright-core ${version}: end marker not found after ${startMarker}`);
  return bundle.slice(start + startMarker.length, end);
}

function injectedScript() {
  const moduleStart = bundle.indexOf('"packages/playwright-core/src/generated/injectedScriptSource.ts"() {');
  const literal = "'" + slice("source5 = '", "';\n", moduleStart) + "'";
  const source = Function(`return ${literal}`)();
  return [
    `// Generated by scripts/build-extension.js from playwright-core ${version} (Apache-2.0). Do not edit.`,
    "// Defines globalThis.__bctlInjectedScriptClass once per isolated world.",
    "(() => {",
    "  if (globalThis.__bctlInjectedScriptClass) return;",
    "  const module = {};",
    source,
    "  globalThis.__bctlInjectedScriptClass = module.exports.InjectedScript();",
    "})();",
    "",
  ].join("\n");
}

function keyboardLayout() {
  const layoutSource = "{" + slice("USKeyboardLayout = {", "\n    };") + "\n}";
  /** @type {Record<string, {key: string, keyCode?: number, keyCodeWithoutLocation?: number, shiftKey?: string, shiftKeyCode?: number, text?: string, location?: number}>} */
  const layout = Function(`return ${layoutSource}`)();
  const aliases = { ShiftLeft: ["Shift"], ControlLeft: ["Control"], AltLeft: ["Alt"], MetaLeft: ["Meta"], Enter: ["\n", "\r"] };
  /** @type {Record<string, object>} */
  const keys = {};
  for (const [code, def] of Object.entries(layout)) {
    const description = {
      key: def.key || "",
      keyCode: def.keyCode || 0,
      code,
      text: def.key.length === 1 ? def.key : def.text || "",
      location: def.location || 0,
    };
    const shifted = def.shiftKey
      ? { ...description, key: def.shiftKey, text: def.shiftKey, keyCode: def.shiftKeyCode || description.keyCode }
      : undefined;
    keys[code] = { ...description, shifted };
    for (const alias of /** @type {Record<string, string[]>} */ (aliases)[code] ?? []) keys[alias] = description;
    if (description.location) continue;
    if (description.key.length === 1) keys[description.key] = description;
    if (shifted) keys[shifted.key] = { ...shifted, shifted: undefined };
  }
  return { generatedFrom: `playwright-core ${version}`, keys };
}

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "pw-injected.js"), injectedScript());
fs.writeFileSync(path.join(outDir, "keyboard-layout.json"), JSON.stringify(keyboardLayout(), null, 1) + "\n");
console.log(`extension/generated/ written from playwright-core ${version}`);
